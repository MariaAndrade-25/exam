#include <unistd.h>

void	alpha_mirror(char *str)
{
	int	i;

	i = 0;
	while (str[i] != '\0')
	{
		if (str[i] >= 'a' && str[i] <= 'z')
			str[i] = 219 - str[i];
		if (str[i] >= 'A' && str[i] <= 'Z')
			str[i] = 155 - str[i];
		write(1, &str[i], 1);
		i++;
	}
}
